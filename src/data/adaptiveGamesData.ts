export function getRecommendedLevelForGrade(grade?: GradeLevel): number {
  if (!grade) return 1;
  const match = ADAPTIVE_LEVELS_META.find(lvl => lvl.gradeKeys.includes(grade));
  return match ? match.levelNumber : 1;
}

